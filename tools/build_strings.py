#!/usr/bin/env python3
"""Writes the app's texts for every language from tools/strings/*.py (one module per screen).

Each module holds STRINGS = [(name, en, tr, nl), ...] and optionally
PLURALS = [(name, {"one": en1, "other": en}, {"other": tr}, {"one": nl1, "other": nl}), ...].
Format placeholders use Android's %1$s / %1$d. Run it after editing a module; --check fails when
res/values*/strings.xml is not what the modules say (CI runs that).
"""

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = sorted((ROOT / "tools" / "strings").glob("*.py"))
RES = ROOT / "app" / "src" / "main" / "res"
LANGS = {"en": "values", "tr": "values-tr", "nl": "values-nl"}
# Texts that are never translated (names, the share-sheet entry keeps its own place here too).
FIXED = [
    ("app_name", "ComApp", None, None),
]


def escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def load():
    strings, plurals, seen = list(FIXED), [], set()
    for path in MODULES:
        spec = importlib.util.spec_from_file_location(path.stem, path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        for entry in getattr(module, "STRINGS", []):
            strings.append(entry)
        for entry in getattr(module, "PLURALS", []):
            plurals.append(entry)
    for name, *_ in strings + plurals:
        if name in seen:
            sys.exit("duplicate string name: %s" % name)
        seen.add(name)
    return strings, plurals


def render(lang, strings, plurals):
    index = list(LANGS).index(lang)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by tools/build_strings.py from tools/strings/; edit those, not this. -->",
             "<resources>"]
    for name, *texts in strings:
        text = texts[index]
        if text is None:
            if lang != "en":
                continue
            text = texts[0]
        attrs = ' translatable="false"' if texts[1] is None and texts[2] is None else ""
        if "%" in text and "%1$" not in text and "%%" not in text:
            attrs += ' formatted="false"'
        lines.append('    <string name="%s"%s>%s</string>' % (name, attrs, escape(text)))
    for name, *forms in plurals:
        lines.append('    <plurals name="%s">' % name)
        for quantity, text in forms[index].items():
            lines.append('        <item quantity="%s">%s</item>' % (quantity, escape(text)))
        lines.append("    </plurals>")
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main():
    strings, plurals = load()
    for name, en, tr, nl in strings:
        if (tr is None) != (nl is None):
            sys.exit("%s: give both translations or neither" % name)
    stale = []
    for lang, folder in LANGS.items():
        path = RES / folder / "strings.xml"
        text = render(lang, strings, plurals)
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        sys.exit("out of date (run tools/build_strings.py): " + ", ".join(stale))
    print("%d strings, %d plurals" % (len(strings), len(plurals)))


if __name__ == "__main__":
    main()
